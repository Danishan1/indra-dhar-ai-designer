import { z } from 'zod';

import { sourcePlacementSchema } from './shape.js';

/**
 * Flat pattern pieces (demo track, ADR-056). A garment **component** (a cuff) and its **pattern
 * piece(s)** (the flat cutting template) are different things: pieces point at their component.
 * Coordinates are millimetres in the piece's own space (x right, y down), the outline is the seam
 * (stitching) line; the seam allowance is added outside it when cutting.
 *
 * Pieces are never manufacturing-accurate by default: `status` stays `provisional` until a person
 * confirms them, and `source` says where they came from (extracted from an uploaded pattern,
 * inferred from a reference, generated by drafting/AI, copied from the library, or drawn by a user).
 */

export const pointSchema = z.object({ x: z.number().finite(), y: z.number().finite() });
export type PatternPoint = z.infer<typeof pointSchema>;

export const PatternSources = ['extracted', 'inferred', 'generated', 'library', 'user'] as const;
export const patternSourceSchema = z.enum(PatternSources);
export type PatternSource = z.infer<typeof patternSourceSchema>;

export const PatternStatuses = ['provisional', 'needs_review', 'confirmed'] as const;
export const patternStatusSchema = z.enum(PatternStatuses);
export type PatternStatus = z.infer<typeof patternStatusSchema>;

const segmentSchema = z.object({ from: pointSchema, to: pointSchema });

export const patternPieceSchema = z.object({
  pieceId: z.string().regex(/^pat_[a-z0-9]{8,32}$/),
  componentId: z.string().regex(/^cmp_[a-z0-9]{8,32}$/),
  name: z.string().trim().min(1).max(120),
  /** Seam line, closed polygon (mm). */
  outline: z.array(pointSchema).min(3).max(600),
  seamAllowanceMm: z.number().min(0).max(100).nullable().default(10),
  grainline: segmentSchema.nullable().default(null),
  /** Cut on fold along this line (the outline is half the piece). */
  foldLine: segmentSchema.nullable().default(null),
  notches: z.array(pointSchema).max(60).default([]),
  /** Pieces to cut per garment (e.g. 2 for a pair of cuffs). */
  cutQuantity: z.number().int().min(1).max(12).default(1),
  /** Cut as mirrored pairs (left/right). */
  mirrored: z.boolean().default(false),
  /** main · contrast · lining · interfacing · … */
  fabricRole: z.string().trim().min(1).max(40).nullable().default('main'),
  source: patternSourceSchema,
  status: patternStatusSchema.default('provisional'),
  /** How a generated piece was drafted, so it can be redrafted when measurements change. */
  draft: z
    .object({
      method: z.enum(['parametric', 'ai_outline', 'extracted_outline']),
      template: z.string().max(80),
      inputs: z.record(z.string(), z.number().finite()).default({}),
    })
    .nullable()
    .default(null),
  notes: z.array(z.string().max(300)).max(20).default([]),
});
export type PatternPiece = z.infer<typeof patternPieceSchema>;
export type PatternPieceInput = z.input<typeof patternPieceSchema>;

/** Where a component appears in a source image (normalized 0–1), for crops and overlays. */
export const sourceRegionSchema = z.object({
  assetId: z.string().trim().min(1).max(200),
  x: z.number().min(0).max(1),
  y: z.number().min(0).max(1),
  width: z.number().min(0).max(1),
  height: z.number().min(0).max(1),
});
export type SourceRegion = z.infer<typeof sourceRegionSchema>;

/** Images a design was started from (sketch, reference, pattern, fabric). */
export const DesignSourceRoles = ['sketch', 'reference', 'pattern', 'fabric', 'other'] as const;
export const designSourceSchema = z.object({
  assetId: z.string().trim().min(1).max(200),
  role: z.enum(DesignSourceRoles),
  label: z.string().max(120).nullable().default(null),
  /** Where the image sits in the garment frame, for the overlay comparison (ADR-057). */
  placement: sourcePlacementSchema.optional(),
});
export type DesignSource = z.infer<typeof designSourceSchema>;

/** Bounding box of an outline (mm). */
export function outlineBounds(points: readonly PatternPoint[]): {
  x: number;
  y: number;
  width: number;
  height: number;
} {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const p of points) {
    minX = Math.min(minX, p.x);
    minY = Math.min(minY, p.y);
    maxX = Math.max(maxX, p.x);
    maxY = Math.max(maxY, p.y);
  }
  if (!Number.isFinite(minX)) return { x: 0, y: 0, width: 0, height: 0 };
  return { x: minX, y: minY, width: maxX - minX, height: maxY - minY };
}
